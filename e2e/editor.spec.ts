import { expect, test } from '@playwright/test'
import { api, probeDownloadedFile, waitJob } from './helpers'

test('real editor supports exact multiple ranges, preview, reload and export', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Загрузить файл', exact: true })).toBeEnabled()
  await page.screenshot({ path: testInfo.outputPath('desktop-empty.png'), fullPage: true })
  await testInfo.attach('Desktop empty state', { path: testInfo.outputPath('desktop-empty.png'), contentType: 'image/png' })
  await page.locator('input[type=file]').setInputFiles(process.env.CUTMY_E2E_MEDIA!)
  const video = page.locator('video')
  await expect(video).toBeVisible()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).duration)).toBeCloseTo(12, 1)

  const start = page.getByLabel('Начало', { exact: true })
  const end = page.getByLabel('Конец', { exact: true })
  await start.fill('00:00:01.250')
  await start.press('Tab')
  await end.fill('00:00:03.750')
  await end.press('Tab')
  await expect(page.getByRole('slider', { name: 'Начало фрагмента на шкале' })).toHaveAttribute('aria-valuenow', '1250')
  await page.getByRole('button', { name: 'Добавить фрагмент', exact: true }).click()
  await start.fill('00:00:06.000')
  await start.press('Tab')
  await end.fill('00:00:08.500')
  await end.press('Tab')

  await page.reload()
  await expect(start).toHaveValue('00:00:06.000')
  await expect(end).toHaveValue('00:00:08.500')
  await expect(video).toBeVisible()
  await page.getByRole('button', { name: 'Посмотреть фрагмент', exact: true }).click()
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(6)
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(false)
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused), { timeout: 8000 }).toBe(true)
  const previewEnd = await video.evaluate(element => (element as HTMLVideoElement).currentTime)
  expect(previewEnd).toBeGreaterThanOrEqual(8.5)
  expect(previewEnd).toBeLessThan(9)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('desktop-editor.png'), fullPage: true })
  await testInfo.attach('Desktop editor', { path: testInfo.outputPath('desktop-editor.png'), contentType: 'image/png' })

  const createResponse = page.waitForResponse(response => response.url().endsWith(`${api}/jobs`) && response.request().method() === 'POST')
  await page.getByRole('button', { name: /Вырезать/ }).click()
  const response = await createResponse
  expect(response.ok()).toBeTruthy()
  expect(response.request().postDataJSON().ranges.map((range: any) => [range.start_ms, range.end_ms])).toEqual([[1250, 3750], [6000, 8500]])
  const job = await waitJob(page.request, (await response.json()).id)
  expect(job.status, JSON.stringify(job)).toBe('succeeded')
  await expect(page.getByRole('link', { name: /Скачать/ }).first()).toBeVisible()
  await probeDownloadedFile(page.request, job.items[0].artifact.download_url, 'ui-export.mp4', testInfo)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('desktop-results.png'), fullPage: true })
  await testInfo.attach('Desktop results', { path: testInfo.outputPath('desktop-results.png'), contentType: 'image/png' })
  expect(errors).toEqual([])
})

test('range handles support keyboard and invalid time input can be corrected', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Загрузить файл', exact: true })).toBeEnabled()
  await page.locator('input[type=file]').setInputFiles(process.env.CUTMY_E2E_MEDIA!)
  const start = page.getByLabel('Начало', { exact: true })
  await expect(start).toBeVisible()
  const handle = page.getByRole('slider', { name: 'Начало фрагмента на шкале' })
  await handle.focus()
  await handle.press('ArrowRight')
  await expect(handle).toHaveAttribute('aria-valuenow', '100')
  await handle.press('Home')
  await expect(handle).toHaveAttribute('aria-valuenow', '0')
  await handle.press('Tab')
  await expect(page.getByRole('slider', { name: 'Конец фрагмента на шкале' })).toBeFocused()

  await start.fill('not-a-time')
  await start.press('Tab')
  await expect(start).toHaveValue('not-a-time')
  await expect(start).toHaveAttribute('aria-invalid', 'true')
  const submittedJobs: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith(`${api}/jobs`)) submittedJobs.push(request.url()) })
  const exportButton = page.getByRole('button', { name: /Вырезать/ })
  if (!(await exportButton.isDisabled())) {
    await exportButton.click()
    await expect(start).toBeFocused()
  }
  await expect(page.getByRole('alert')).toContainText('Введите время')
  expect(submittedJobs).toEqual([])
  await start.fill('00:00:02.000')
  await start.press('Tab')
  await expect(handle).toHaveAttribute('aria-valuenow', '2000')
  await expect(page.getByRole('button', { name: /Вырезать/ })).toBeEnabled()
})

test('replacing a source resets selections belonging to the old video', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Загрузить файл', exact: true })).toBeEnabled()
  await page.locator('input[type=file]').setInputFiles(process.env.CUTMY_E2E_MEDIA!)
  const start = page.getByLabel('Начало', { exact: true })
  await expect(start).toBeVisible()
  await start.fill('00:00:04.000')
  await start.press('Tab')
  await page.getByRole('button', { name: 'Добавить фрагмент', exact: true }).click()
  await expect(page.locator('.range-list > li')).toHaveCount(2)
  const responsePromise = page.waitForResponse(response => response.url().endsWith(`${api}/uploads`) && response.request().method() === 'POST')
  await page.locator('input[type=file]').setInputFiles(process.env.CUTMY_E2E_MEDIA!)
  expect((await responsePromise).ok()).toBeTruthy()
  await expect(start).toHaveValue('00:00:00.000')
  await expect(page.getByLabel('Конец', { exact: true })).toHaveValue('00:00:12.000')
  await expect(page.locator('.range-list > li')).toHaveCount(1)
})

test('an active UI export survives reload and can be cancelled', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Загрузить файл', exact: true })).toBeEnabled()
  await page.locator('input[type=file]').setInputFiles(process.env.CUTMY_E2E_MEDIA!)
  const add = page.getByRole('button', { name: 'Добавить фрагмент', exact: true })
  await expect(add).toBeVisible()
  for (let i = 0; i < 9; i++) await add.click()
  const creationPromise = page.waitForResponse(response => response.url().endsWith(`${api}/jobs`) && response.request().method() === 'POST')
  await page.getByRole('button', { name: /Вырезать/ }).click()
  const creation = await creationPromise
  expect(creation.ok()).toBeTruthy()
  const id = (await creation.json()).id
  const cancel = page.getByRole('button', { name: 'Отменить обработку', exact: true })
  await expect(cancel).toBeVisible()
  await expect.poll(async () => (await (await page.request.get(`${api}/jobs/${id}`)).json()).status, { intervals: [100, 100, 200] }).toBe('running')
  await expect(page.getByLabel('Ссылка на видео', { exact: true })).toBeDisabled()
  await page.reload()
  await expect(cancel).toBeVisible()
  await cancel.click()
  const terminal = await waitJob(page.request, id)
  expect(terminal.status).toBe('cancelled')
  await expect(page.getByRole('heading', { name: 'Обработка отменена', exact: true })).toBeVisible()
  await expect(page.getByLabel('Ссылка на видео', { exact: true })).toBeEnabled()
})

test('a real three-hour source supports a precise middle selection and export', async ({ page }, testInfo) => {
  test.skip(!process.env.CUTMY_E2E_LONG_MEDIA, 'Set CUTMY_E2E_LONG_MEDIA to a real three-hour fixture.')
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Загрузить файл', exact: true })).toBeEnabled()
  await page.locator('input[type=file]').setInputFiles(process.env.CUTMY_E2E_LONG_MEDIA!)
  await expect.poll(() => page.locator('video').evaluate(element => (element as HTMLVideoElement).duration)).toBeCloseTo(10_800, 0)
  await page.getByLabel('Начало', { exact: true }).fill('01:23:10.000')
  await page.getByLabel('Начало', { exact: true }).press('Tab')
  await page.getByLabel('Конец', { exact: true }).fill('01:23:40.000')
  await page.getByLabel('Конец', { exact: true }).press('Tab')
  await expect(page.getByRole('slider', { name: 'Начало фрагмента на шкале' })).toHaveAttribute('aria-valuenow', '4990000')
  await expect(page.getByRole('slider', { name: 'Конец фрагмента на шкале' })).toHaveAttribute('aria-valuenow', '5020000')
  await page.getByLabel('Масштаб шкалы', { exact: true }).selectOption('60000')
  const track = await page.locator('.trim-track').boundingBox()
  const selected = await page.locator('.trim-selection').boundingBox()
  expect(track).toBeTruthy()
  expect(selected).toBeTruthy()
  expect(selected!.width / track!.width).toBeGreaterThan(0.4)
  expect(selected!.width / track!.width).toBeLessThan(0.6)
  const responsePromise = page.waitForResponse(response => response.url().endsWith(`${api}/jobs`) && response.request().method() === 'POST')
  await page.getByRole('button', { name: /Вырезать/ }).click()
  const creation = await responsePromise
  expect(creation.ok()).toBeTruthy()
  const job = await waitJob(page.request, (await creation.json()).id)
  expect(job.status, JSON.stringify(job)).toBe('succeeded')
  const probe = await probeDownloadedFile(page.request, job.items[0].artifact.download_url, 'three-hour-middle.mp4', testInfo)
  expect(Math.abs(Number(probe.format.duration) - 30)).toBeLessThan(0.2)
  expect(job.items[0].artifact.actual_start_ms).toBe(4_990_000)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('three-hour-editor.png'), fullPage: true })
  await testInfo.attach('Three-hour source', { path: testInfo.outputPath('three-hour-editor.png'), contentType: 'image/png' })
})
