import { execFileSync } from 'node:child_process'
import { expect, test } from '@playwright/test'
import { addClip, chooseOption, goToExport, probeDownloadedFile, saveClip, showExactTimes, uploadThroughUI, waitJob, showExportSettings, closeExportSettings } from './helpers'

test('real joined MKV keeps selected audio and rebased subtitles; separate no-sound files decode', async ({ page }, testInfo) => {
  await page.goto('/?lang=en')
  await uploadThroughUI(page, process.env.CUTMY_E2E_MULTITRACK!)
  await showExactTimes(page)
  const start = page.getByLabel('Start', { exact: true })
  const end = page.getByLabel('End', { exact: true })
  await start.fill('00:00:08.000'); await start.press('Tab')
  await end.fill('00:00:11.000'); await end.press('Tab')
  await showExportSettings(page)
  await chooseOption(page, page.locator('#audio-track-export'), /Audio #1.*rus.*aac/)
  await closeExportSettings(page)
  await saveClip(page)
  await addClip(page)
  await showExactTimes(page)
  await start.fill('00:00:01.000'); await start.press('Tab')
  await end.fill('00:00:04.000'); await end.press('Tab')
  await closeExportSettings(page)
  await saveClip(page)
  await showExportSettings(page)
  await chooseOption(page, page.locator('#output-mode'), 'One joined file')
  await chooseOption(page, page.locator('#cut-mode'), 'Original quality')
  await chooseOption(page, page.locator('#copy-container'), 'MKV')
  await chooseOption(page, page.locator('#subtitle-mode'), 'Preserve text subtitles')
  // This scenario deliberately reuses its original for a second export.
  const cleanup = page.getByRole('checkbox', { name: 'Delete source after export', exact: true })
  await cleanup.uncheck()
  await expect(cleanup).not.toBeChecked()
  await closeExportSettings(page)
  const accepted = page.waitForResponse(response => response.url().endsWith('/api/v1/jobs') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Cut clips', exact: true }).click()
  const response = await accepted
  expect(response.ok(), await response.text()).toBeTruthy()
  const created = await response.json()
  const joined = await waitJob(page.request, created.id)
  expect(joined.status, JSON.stringify(joined)).toBe('succeeded')
  expect(joined.items).toHaveLength(1)
  const artifact = joined.items[0].artifact
  const details = await probeDownloadedFile(page.request, artifact.download_url, 'joined-selected.mkv', testInfo)
  expect(details.streams.filter((stream: any) => stream.codec_type === 'audio')).toHaveLength(1)
  expect(details.streams.find((stream: any) => stream.codec_type === 'audio').tags.language).toBe('rus')
  expect(details.streams.find((stream: any) => stream.codec_type === 'video').codec_name).toBe('h264')
  expect(details.streams.find((stream: any) => stream.codec_type === 'subtitle').codec_name).toBe('subrip')
  expect(Number(details.format.duration)).toBeGreaterThan(5.8)
  expect(Number(details.format.duration)).toBeLessThan(6.3)
  const filename = testInfo.outputPath('joined-selected.mkv')
  execFileSync('ffmpeg', ['-v', 'error', '-xerror', '-i', filename, '-f', 'null', '-'], { timeout: 30_000 })
  const samples = execFileSync('ffmpeg', ['-v', 'error', '-ss', '0.5', '-i', filename, '-map', '0:a:0', '-t', '1', '-ac', '1', '-ar', '8000', '-f', 's16le', '-'], { timeout: 30_000 })
  let crossings = 0
  for (let offset = 2; offset < samples.length; offset += 2) if ((samples.readInt16LE(offset - 2) < 0) !== (samples.readInt16LE(offset) < 0)) crossings++
  expect(crossings / 2).toBeGreaterThan(430)
  expect(crossings / 2).toBeLessThan(450)
  const captions = execFileSync('ffmpeg', ['-v', 'error', '-i', filename, '-map', '0:s:0', '-f', 'srt', '-'], { encoding: 'utf8', timeout: 30_000 })
  expect(captions.indexOf('Later caption')).toBeLessThan(captions.indexOf('Opening caption'))
  expect(captions).toMatch(/00:00:01,[0-9]{3} --> 00:00:02,[0-9]{3}/)
  expect(captions).toMatch(/00:00:04,[0-9]{3} --> 00:00:05,[0-9]{3}/)
  expect(artifact.segments.map((segment: any) => segment.source_start_ms)).toEqual([8000, 1000])
  await expect(page.getByRole('heading', { name: 'Joined result' })).toBeVisible()
  await page.locator('.file-description .artifact-details summary').click()
  await expect(page.locator('.file-description')).toContainText('Included: Audio #1')

  await showExportSettings(page)
  await chooseOption(page, page.locator('#output-mode'), 'Separate files')
  await chooseOption(page, page.locator('#subtitle-mode'), 'Omit subtitles')
  await chooseOption(page, page.locator('#copy-container'), 'MP4')
  await chooseOption(page, page.locator('#cut-mode'), 'Exact boundaries')
  await chooseOption(page, page.locator('#audio-track-export'), 'No sound')
  await closeExportSettings(page)
  const silentAccepted = page.waitForResponse(response => response.url().endsWith('/api/v1/jobs') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Cut clips', exact: true }).click()
  const silentResponse = await silentAccepted
  expect(silentResponse.ok(), await silentResponse.text()).toBeTruthy()
  const silent = await waitJob(page.request, (await silentResponse.json()).id)
  expect(silent.status, JSON.stringify(silent)).toBe('succeeded')
  expect(silent.items).toHaveLength(2)
  for (const [index, item] of silent.items.entries()) {
    const output = await probeDownloadedFile(page.request, item.artifact.download_url, 'silent-' + index + '.mp4', testInfo)
    expect(output.streams.map((stream: any) => stream.codec_type)).toEqual(['video'])
    execFileSync('ffmpeg', ['-v', 'error', '-xerror', '-i', testInfo.outputPath('silent-' + index + '.mp4'), '-f', 'null', '-'], { timeout: 30_000 })
  }
  expect(silent.items[0].artifact.actual_start_ms).toBe(8000)
  expect(silent.items[1].artifact.actual_start_ms).toBe(1000)
})
