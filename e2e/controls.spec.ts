import { expect, test } from '@playwright/test'
import { chooseOption, goToExport, goToMoment, showExactTimes, uploadThroughUI } from './helpers'

test('custom selectors support keyboard choice, typeahead, Escape and native-dialog focus', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'English', exact: true }).click()
  const settings = page.getByRole('button', { name: 'Settings', exact: true })
  await settings.click()
  const dialog = page.getByRole('dialog')
  const theme = dialog.getByRole('combobox', { name: 'Appearance', exact: true })
  await theme.focus()
  await theme.press('Enter')
  const list = dialog.getByRole('listbox')
  await expect(list).toBeVisible()
  await expect(dialog.locator('#theme-preference')).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('End')
  await expect(list.getByRole('option', { name: 'Dark', exact: true })).toBeFocused()
  await page.keyboard.press('Home')
  await expect(list.getByRole('option', { name: 'System', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(list).not.toBeVisible()
  await expect(dialog).toBeVisible()
  await expect(theme).toBeFocused()
  await expect(theme).toContainText('System')
  await theme.press('Space')
  await expect(list).toBeVisible()
  await page.keyboard.press('d')
  await expect(list.getByRole('option', { name: 'Dark', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(theme).toContainText('Dark')
  await expect(theme).toBeFocused()
  await dialog.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(settings).toBeFocused()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await uploadThroughUI(page)
  await goToExport(page)
  const quality = page.getByRole('combobox', { name: 'Video quality', exact: true })
  await quality.focus()
  await quality.press('ArrowDown')
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await expect(quality).toContainText('Best available')
  await expect(quality).toBeFocused()
  await chooseOption(page, page.getByRole('combobox', { name: 'Boundaries and quality', exact: true }), 'Original quality')
  await expect(quality).toBeDisabled()
  await expect(quality).toContainText('Original quality')
  await expect(page.getByText('No re-encoding. Boundaries may shift; some codecs are incompatible with MP4.', { exact: true })).toBeVisible()
  await chooseOption(page, page.getByRole('combobox', { name: 'Boundaries and quality', exact: true }), 'Exact boundaries')
  await expect(quality).toBeEnabled()
  await goToMoment(page)
  await showExactTimes(page)
  await page.locator('#range-start').fill('00:00:01.250')
  await page.locator('#range-start').press('Tab')
  await page.locator('#range-end').fill('00:00:03.750')
  await page.locator('#range-end').press('Tab')
  const video = page.locator('video')
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).duration)).toBeCloseTo(12, 1)
  await video.evaluate(element => { (element as HTMLVideoElement).currentTime = 2.5 })
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).seeking)).toBe(false)
  await expect(page.locator('#overview')).toHaveValue('2500')
  const zoom = page.getByRole('combobox', { name: 'Timeline zoom', exact: true })
  for (const key of ['i', 'o', 'Space']) {
    await zoom.focus()
    await zoom.press('Enter')
    await expect(page.getByRole('listbox')).toBeVisible()
    await page.keyboard.press(key)
    await expect(page.locator('.trim-handle.start')).toHaveAttribute('aria-valuenow', '1250')
    await expect(page.locator('.trim-handle.end')).toHaveAttribute('aria-valuenow', '3750')
    expect(await video.evaluate(element => (element as HTMLVideoElement).paused), `${key} in a select popup must not play media`).toBe(true)
    if (await page.getByRole('listbox').isVisible()) await page.keyboard.press('Escape')
    await expect(zoom).toBeFocused()
  }
  await settings.click()
  await theme.focus()
  await theme.press('Enter')
  await expect(dialog.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.locator('.trim-handle.start')).toHaveAttribute('aria-valuenow', '1250')
  await expect(page.locator('.trim-handle.end')).toHaveAttribute('aria-valuenow', '3750')
  expect(await video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(true)
  if (await dialog.getByRole('listbox').isVisible()) await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  // The same shortcuts remain useful in the editor outside fields and menus.
  await page.locator('.page-heading h1').focus()
  await page.keyboard.press('i')
  await expect(page.locator('#range-start')).toHaveValue('00:00:02.500')
  await video.evaluate(element => { (element as HTMLVideoElement).currentTime = 3 })
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).seeking)).toBe(false)
  await expect(page.locator('#overview')).toHaveValue('3000')
  await page.locator('.page-heading h1').focus()
  await page.keyboard.press('o')
  await expect(page.locator('#range-end')).toHaveValue('00:00:03.000')
  await page.keyboard.press('Space')
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(3.1)
  await page.keyboard.press('Space')
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).paused)).toBe(true)
})

test('dismissed export menus keep the chosen value and do not create a job', async ({ page }) => {
  await page.goto('/')
  await uploadThroughUI(page)
  await goToExport(page)
  const jobs: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/v1\/jobs$/.test(request.url())) jobs.push(request.url()) })
  const quality = page.getByRole('combobox', { name: 'Качество видео', exact: true })
  await chooseOption(page, quality, 'До 720p')
  await quality.click()
  await expect(page.getByRole('listbox')).toBeVisible()
  const outside = await page.locator('.page-heading h1').boundingBox()
  expect(outside).not.toBeNull()
  await page.mouse.click(outside!.x + outside!.width / 2, outside!.y + outside!.height / 2)
  await expect(page.getByRole('listbox')).not.toBeVisible()
  await expect(quality).toContainText('720p')
  await quality.focus()
  await quality.press('ArrowDown')
  await page.keyboard.press('End')
  await page.keyboard.press('Escape')
  await expect(quality).toBeFocused()
  await expect(quality).toContainText('720p')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('combobox', { name: 'Границы и качество', exact: true })).toBeFocused()
  expect(jobs).toEqual([])
})
