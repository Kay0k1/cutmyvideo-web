async function disclose(section: Locator) {
  await expect(section).toBeVisible()
  if (!await section.evaluate(node => (node as HTMLDetailsElement).open)) await section.locator(':scope > summary').click()
}

async function analysisSection(page: Page, label: string) {
  await showEditorTools(page)
  const section = page.locator('.media-analysis-tools details').filter({ has: page.locator('summary').filter({ hasText: label }) }).first()
  await disclose(section)
  return section
}

async function enhancements(page: Page) {
  await showExportSettings(page)
  const panel = page.locator('.export-enhancements')
  await disclose(panel)
  return panel
}

async function enhancementSection(page: Page, label: string) {
  const panel = await enhancements(page)
  const section = panel.locator('details').filter({ has: page.locator('summary').filter({ hasText: label }) }).first()
  await disclose(section)
  return section
}

async function clipBounds(page: Page) {
  return (await savedMediaDraft(page))?.ranges?.map((range: any) => ({ label: range.label, start_ms: range.start_ms, end_ms: range.end_ms })) ?? []
}

async function selectedWindow(page: Page, start: string, end: string) {
  await showExactTimes(page)
  const first = page.getByLabel('Начало', { exact: true }), last = page.getByLabel('Конец', { exact: true })
  await first.fill(start); await first.press('Tab'); await last.fill(end); await last.press('Tab')
  await readBrowserDraft(page)
}

