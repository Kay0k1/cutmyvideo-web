  expect(chapters.text).toContain('START=2000')
  expect(chapters.text).toContain('END=4000')
  expect(chapters.text).not.toContain('START=4000')
  await testInfo.attach('actual-transform-checks.json', { body: JSON.stringify({ submitted: body, loudness, pad_rgb: [...pixel], original_loudness: originalLoudness }, null, 2), contentType: 'application/json' })
