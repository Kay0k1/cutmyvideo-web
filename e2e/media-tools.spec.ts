  expect(await clipBounds(page)).toEqual(original)
  gate = new Promise<void>(resolve => { releaseResponse = resolve })
  fetched = new Promise<void>(resolve => { responseFetched = resolve })
  complete = new Promise<void>(resolve => { handled = resolve })
